"""Configuration loading, environment expansion, and validation for mcpx-gateway.

Fits into MCPX by parsing `/config/config.json` (generated by `scripts/mcp-servers.sh`)
into strongly typed gateway settings, upstream server specs, and group allow-lists
used by `upstream.py`, `router.py`, and `app.py`.
"""

from __future__ import annotations

from dataclasses import dataclass
import json
import os
from pathlib import Path
import re
from typing import Any, Literal

_ENV_VAR_RE = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}")
_DURATION_RE = re.compile(r"^\s*(\d+(?:\.\d+)?)\s*(ms|s|m|h)?\s*$", re.IGNORECASE)
_PATH_SEGMENT_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
_RESERVED_SERVER_NAMES = frozenset({"mcp", "groups", "oauth", "_healthz", "_readyz"})

TransportType = Literal["stdio", "streamable-http"]


class ConfigError(ValueError):
    """Raised when the mcpx-gateway configuration file is invalid."""


@dataclass(frozen=True)
class GatewaySettings:
    name: str
    version: str
    host: str
    port: int
    startup_grace_period: float
    ping_interval: float
    reconnect_interval: float
    auth_tokens: tuple[str, ...]


@dataclass(frozen=True)
class ServerConfig:
    name: str
    transport: TransportType
    command: str | None
    args: tuple[str, ...]
    env: dict[str, str]
    url: str | None
    headers: dict[str, str]
    timeout: float


@dataclass(frozen=True)
class GroupConfig:
    name: str
    description: str
    servers: dict[str, Literal["*"] | tuple[str, ...]]


@dataclass(frozen=True)
class GatewayConfig:
    gateway: GatewaySettings
    servers: dict[str, ServerConfig]
    groups: dict[str, GroupConfig]


def _expand_env(value: Any) -> Any:
    """Recursively expand `${ENV_VAR}` placeholders in string values."""
    if isinstance(value, str):
        return _ENV_VAR_RE.sub(lambda m: os.environ.get(m.group(1), ""), value)
    if isinstance(value, list):
        return [_expand_env(item) for item in value]
    if isinstance(value, dict):
        return {k: _expand_env(v) for k, v in value.items()}
    return value


def parse_duration(value: Any, field_name: str) -> float:
    """Parse seconds from a positive int/float or duration string such as '60s'."""
    if isinstance(value, bool):
        raise ConfigError(f"'{field_name}' must be a positive number or duration string")
    if isinstance(value, (int, float)):
        seconds = float(value)
    elif isinstance(value, str):
        match = _DURATION_RE.match(value)
        if not match:
            raise ConfigError(f"Invalid duration '{value}' for '{field_name}'")
        amount = float(match.group(1))
        unit = (match.group(2) or "s").lower()
        multipliers = {"ms": 0.001, "s": 1.0, "m": 60.0, "h": 3600.0}
        seconds = amount * multipliers[unit]
    else:
        raise ConfigError(f"'{field_name}' must be a positive number or duration string")

    if seconds <= 0:
        raise ConfigError(f"'{field_name}' must be greater than 0")
    return seconds


def _validate_identifier(name: Any, kind: str) -> str:
    if not isinstance(name, str) or not _PATH_SEGMENT_RE.match(name):
        raise ConfigError(
            f"Invalid {kind} name {name!r}: must be a single URL-safe segment matching {_PATH_SEGMENT_RE.pattern}"
        )
    return name


def _parse_string_map(raw: Any, field_name: str) -> dict[str, str]:
    if raw is None:
        return {}
    if not isinstance(raw, dict):
        raise ConfigError(f"'{field_name}' must be an object mapping strings to strings")
    result: dict[str, str] = {}
    for key, val in raw.items():
        if not isinstance(key, str) or not isinstance(val, str):
            raise ConfigError(f"'{field_name}' entries must have string keys and string values")
        result[key] = val
    return result


def _parse_gateway(raw: Any) -> GatewaySettings:
    if raw is None:
        raw = {}
    if not isinstance(raw, dict):
        raise ConfigError("'gateway' must be a JSON object")

    name = raw.get("name", "MCPX Gateway")
    version = raw.get("version", "1.0.0")
    host = raw.get("host", "0.0.0.0")
    port = raw.get("port", 9000)

    if not isinstance(name, str) or not name.strip():
        raise ConfigError("'gateway.name' must be a non-empty string")
    if not isinstance(version, str) or not version.strip():
        raise ConfigError("'gateway.version' must be a non-empty string")
    if not isinstance(host, str) or not host.strip():
        raise ConfigError("'gateway.host' must be a non-empty string")
    if isinstance(port, bool) or not isinstance(port, int) or not (1 <= port <= 65535):
        raise ConfigError("'gateway.port' must be an integer between 1 and 65535")

    startup_grace = parse_duration(raw.get("startupGracePeriod", 90), "gateway.startupGracePeriod")
    ping_interval = parse_duration(raw.get("pingInterval", 30), "gateway.pingInterval")
    reconnect_interval = parse_duration(raw.get("reconnectInterval", 15), "gateway.reconnectInterval")

    raw_tokens = raw.get("authTokens", [])
    if not isinstance(raw_tokens, list) or not all(isinstance(t, str) for t in raw_tokens):
        raise ConfigError("'gateway.authTokens' must be a list of strings")
    auth_tokens = tuple(t.strip() for t in raw_tokens if t.strip())

    return GatewaySettings(
        name=name.strip(),
        version=version.strip(),
        host=host.strip(),
        port=port,
        startup_grace_period=startup_grace,
        ping_interval=ping_interval,
        reconnect_interval=reconnect_interval,
        auth_tokens=auth_tokens,
    )


def _parse_server(name: str, raw: Any) -> ServerConfig:
    _validate_identifier(name, "server")
    if name in _RESERVED_SERVER_NAMES:
        raise ConfigError(f"Server name '{name}' is reserved")
    if not isinstance(raw, dict):
        raise ConfigError(f"Server '{name}' definition must be a JSON object")

    command = raw.get("command")
    url = raw.get("url")
    transport_raw = raw.get("transportType")

    has_command = command is not None
    has_url = url is not None
    if has_command and has_url:
        raise ConfigError(f"Server '{name}' cannot define both 'command' and 'url'")
    if not has_command and not has_url:
        raise ConfigError(f"Server '{name}' must define either 'command' or 'url'")

    if has_command:
        if not isinstance(command, str) or not command.strip():
            raise ConfigError(f"Server '{name}' has an empty 'command'")
        if transport_raw is not None and transport_raw != "stdio":
            raise ConfigError(f"Server '{name}' with 'command' must use transportType 'stdio'")
        raw_args = raw.get("args", [])
        if not isinstance(raw_args, list) or not all(isinstance(a, str) for a in raw_args):
            raise ConfigError(f"Server '{name}.args' must be a list of strings")
        transport: TransportType = "stdio"
        args = tuple(raw_args)
        env = _parse_string_map(raw.get("env"), f"servers.{name}.env")
        headers: dict[str, str] = {}
        command_val: str | None = command.strip()
        url_val: str | None = None
    else:
        if not isinstance(url, str) or not url.strip().startswith(("http://", "https://")):
            raise ConfigError(f"Server '{name}' must have a valid http(s) 'url'")
        if transport_raw is not None and transport_raw != "streamable-http":
            raise ConfigError(f"Server '{name}' with 'url' must use transportType 'streamable-http'")
        transport = "streamable-http"
        args = ()
        env = {}
        headers = _parse_string_map(raw.get("headers"), f"servers.{name}.headers")
        command_val = None
        url_val = url.strip()

    timeout = parse_duration(raw.get("timeout", 60), f"servers.{name}.timeout")

    return ServerConfig(
        name=name,
        transport=transport,
        command=command_val,
        args=args,
        env=env,
        url=url_val,
        headers=headers,
        timeout=timeout,
    )


def _parse_groups(raw: Any, servers: dict[str, ServerConfig]) -> dict[str, GroupConfig]:
    if raw is None:
        return {}
    if not isinstance(raw, dict):
        raise ConfigError("'groups' must be a JSON object")

    groups: dict[str, GroupConfig] = {}
    for group_name, group_def in raw.items():
        _validate_identifier(group_name, "group")
        if not isinstance(group_def, dict):
            raise ConfigError(f"Group '{group_name}' definition must be a JSON object")

        description = group_def.get("description", "")
        if not isinstance(description, str):
            raise ConfigError(f"Group '{group_name}.description' must be a string")

        raw_servers = group_def.get("servers")
        if not isinstance(raw_servers, dict) or not raw_servers:
            raise ConfigError(f"Group '{group_name}.servers' must be a non-empty object")

        allowed: dict[str, Literal["*"] | tuple[str, ...]] = {}
        for server_name, spec in raw_servers.items():
            if server_name not in servers:
                raise ConfigError(
                    f"Group '{group_name}' references unknown server '{server_name}'"
                )
            if spec == "*":
                allowed[server_name] = "*"
            elif isinstance(spec, list) and spec and all(isinstance(t, str) and t.strip() for t in spec):
                allowed[server_name] = tuple(t.strip() for t in spec)
            else:
                raise ConfigError(
                    f"Group '{group_name}' server '{server_name}' must be '*' or a non-empty list of tool names"
                )

        groups[group_name] = GroupConfig(
            name=group_name,
            description=description,
            servers=allowed,
        )
    return groups


def load_config(path: str | Path) -> GatewayConfig:
    """Load, expand environment variables, and validate the gateway JSON config."""
    config_path = Path(path)
    try:
        raw_text = config_path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ConfigError(f"Unable to read config file '{config_path}': {exc}") from exc

    try:
        raw_data = json.loads(raw_text)
    except json.JSONDecodeError as exc:
        raise ConfigError(f"Invalid JSON in '{config_path}': {exc}") from exc

    if not isinstance(raw_data, dict):
        raise ConfigError("Top-level config must be a JSON object")

    expanded = _expand_env(raw_data)
    gateway = _parse_gateway(expanded.get("gateway"))

    raw_servers = expanded.get("servers")
    if not isinstance(raw_servers, dict) or not raw_servers:
        raise ConfigError("'servers' must be a non-empty JSON object")

    servers = {name: _parse_server(name, spec) for name, spec in raw_servers.items()}
    groups = _parse_groups(expanded.get("groups"), servers)

    return GatewayConfig(gateway=gateway, servers=servers, groups=groups)
